#!/usr/bin/env bash
# =====================================================================================
#  brplayer · actualización de interfaz (diseño pastel responsive)
#
#  Uso (desde la carpeta de tu proyecto, la que tiene package.json):
#      bash update.sh              # aplica los cambios y compila
#      bash update.sh --no-build   # solo aplica los cambios, sin compilar
#      bash update.sh /ruta/proyecto
#
#  Qué hace:
#   1. Comprueba que estás en el proyecto brplayer.
#   2. Guarda una copia de lo que va a reemplazar en .backup-brplayer-<fecha>/
#   3. Escribe los archivos nuevos (interfaz rehecha + correcciones de búsqueda y de iPhone).
#   4. Instala dependencias si faltan, comprueba tipos y compila dist-single/brplayer.html.
# =====================================================================================
set -euo pipefail

BUILD=1
DIR="."
for a in "$@"; do
  case "$a" in
    --no-build) BUILD=0 ;;
    -h|--help) sed -n 2,16p "$0"; exit 0 ;;
    *) DIR="$a" ;;
  esac
done

say()  { printf '\033[1;35m▸\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m✓\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

cd "$DIR" || die "No existe la carpeta: $DIR"
[ -f package.json ] && [ -f src/store/useStore.ts ] && [ -f src/audio/player.ts ] \
  || die "Esto no parece el proyecto brplayer (faltan package.json o src/). Ejecuta el script dentro de la carpeta del proyecto."

# base64 -d en Linux y macOS recientes; -D en macOS antiguos
if echo QQ== | base64 -d >/dev/null 2>&1; then B64D="base64 -d"; else B64D="base64 -D"; fi

# --- 1) copia de seguridad ---------------------------------------------------------
STAMP="$(date +%Y%m%d-%H%M%S)"
BK=".backup-brplayer-$STAMP"
PAYLOAD_LINE="$(awk '/^__PAYLOAD_BELOW__$/ {print NR + 1; exit 0}' "$0")"
[ -n "$PAYLOAD_LINE" ] || die "El script está incompleto (no encuentra los archivos incrustados)."

say "Guardando copia de seguridad en $BK/"
tail -n +"$PAYLOAD_LINE" "$0" | $B64D | tar tzf - | while IFS= read -r f; do
  if [ -f "$f" ]; then mkdir -p "$BK/$(dirname "$f")"; cp -p "$f" "$BK/$f"; fi
done
[ -d "$BK" ] && ok "Copia guardada ($(find "$BK" -type f | wc -l | tr -d ' ') archivos)" || { say "Nada que respaldar"; }

# --- 2) aplicar --------------------------------------------------------------------
say "Aplicando la nueva interfaz…"
tail -n +"$PAYLOAD_LINE" "$0" | $B64D | tar xzf -
ok "Archivos actualizados"

# --- 3) compilar -------------------------------------------------------------------
if [ "$BUILD" = 1 ]; then
  command -v node >/dev/null && command -v npm >/dev/null || die "Hace falta Node.js y npm para compilar. Instálalos o ejecuta con --no-build."
  if [ ! -d node_modules ]; then say "Instalando dependencias (npm install)…"; npm install --no-audit --no-fund; fi
  say "Compilando (tipos + build de un solo archivo)…"
  npm run build:single
  rm -f tsconfig.tsbuildinfo
  ok "Listo: dist-single/brplayer.html"
fi

cat <<MSG

──────────────────────────────────────────────────────────────
 ✅ Actualización aplicada.

 • Probar en local ........ npm run dev
 • Subir al servidor ...... dist-single/brplayer.html  (súbelo como index.html)
                            o: npm run build  y sube la carpeta dist/
 • Volver atrás ........... copia de $BK/ sobre el proyecto

 Nota: tu index.html anterior era un build compilado (no el de
 desarrollo). Ahora index.html es el real, el que usa Vite; por eso
 el archivo que se sube al servidor es el de dist-single/.
──────────────────────────────────────────────────────────────
MSG
exit 0
